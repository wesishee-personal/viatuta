-- +goose Up

-- "crash" collided with the other kind of crash — the process kind — making
-- names like crash_score ambiguous at a glance in logs and in code. The domain
-- noun is now "collision" everywhere.
--
-- Migrations 00002 and 00003 are left as they were written: they are applied
-- history, and rewriting them would make a fresh database disagree with an
-- existing one about what this migration still has to do.

ALTER TABLE crash RENAME TO collision;
ALTER TABLE crash_edge RENAME TO collision_edge;
ALTER TABLE collision_edge RENAME COLUMN crash_id TO collision_id;
ALTER TABLE routing_edge RENAME COLUMN crash_score TO collision_score;

-- Renaming a table or column leaves its sequences and indexes under the old
-- name, so each is renamed explicitly.
ALTER SEQUENCE crash_id_seq RENAME TO collision_id_seq;

ALTER INDEX crash_source_id_idx RENAME TO collision_source_id_idx;
ALTER INDEX crash_geom_idx      RENAME TO collision_geom_idx;
ALTER INDEX crash_cyclist_idx   RENAME TO collision_cyclist_idx;
ALTER INDEX crash_edge_edge_idx RENAME TO collision_edge_edge_idx;

-- Constraint names are generated by Postgres (primary keys, foreign keys,
-- checks, and on PG17+ the NOT NULLs), so they are renamed by pattern rather
-- than listed — the set differs by server version, and these names surface in
-- constraint-violation errors. Renaming a key constraint renames its index too.
-- +goose StatementBegin
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT conname, conrelid::regclass::text AS tbl
        FROM pg_constraint
        WHERE conrelid IN ('collision'::regclass, 'collision_edge'::regclass,
                           'routing_edge'::regclass)
          AND conname LIKE '%crash%'
    LOOP
        EXECUTE format('ALTER TABLE %s RENAME CONSTRAINT %I TO %I',
                       r.tbl, r.conname, replace(r.conname, 'crash', 'collision'));
    END LOOP;
END $$;
-- +goose StatementEnd

